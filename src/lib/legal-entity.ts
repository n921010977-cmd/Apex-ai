// ─── Реквизиты оператора для правовых документов ──────────────────────────────
// Раньше эти значения были вписаны в тексты документов как «[УКАЖИТЕ ...]» и
// показывались посетителям сайта. Незаполненный оператор в политике — это не
// косметика: по закону о персональных данных субъект должен знать, кому именно
// он даёт согласие и куда обращаться за отзывом. Плейсхолдер вместо имени
// оператора делает и согласие, и политику фактически недействительными.
//
// Теперь всё в одном месте: заполняется через переменные окружения, а пока они
// не заданы — документы честно описывают текущее положение (сервис ведёт
// частное лицо, связь по email), а не показывают строку-заглушку.

/** Название оператора: юрлицо/ИП, когда оно появится. */
export const LEGAL_ENTITY =
  process.env.NEXT_PUBLIC_LEGAL_ENTITY?.trim() ||
  "частное лицо, администрирующее сервис Vertlix AI";

/** Юрисдикция/страна регистрации оператора. */
export const LEGAL_JURISDICTION =
  process.env.NEXT_PUBLIC_LEGAL_JURISDICTION?.trim() ||
  "страна регистрации будет указана после регистрации юридического лица";

/** Почтовый/юридический адрес. Пока его нет — единственный канал связи email. */
export const LEGAL_ADDRESS =
  process.env.NEXT_PUBLIC_LEGAL_ADDRESS?.trim() ||
  "почтовый адрес не указан — все обращения принимаются по электронной почте";

/** Применимое право для разрешения споров. */
export const LEGAL_LAW =
  process.env.NEXT_PUBLIC_LEGAL_LAW?.trim() ||
  "право страны постоянного проживания пользователя в части императивных норм о защите прав потребителей";

/** Подсудность. */
export const LEGAL_VENUE =
  process.env.NEXT_PUBLIC_LEGAL_VENUE?.trim() ||
  "нахождения ответчика";

/** Заданы ли настоящие реквизиты — по этому флагу документы показывают предупреждение. */
export const LEGAL_ENTITY_CONFIGURED = Boolean(process.env.NEXT_PUBLIC_LEGAL_ENTITY?.trim());
