// ─── Безопасная подстановка пользовательского текста в PostgREST-фильтр ───────
// `.or("title.ilike.%X%,content.ilike.%X%")` — это строка на языке фильтров
// PostgREST, а не параметризованный запрос. Запятая разделяет условия, скобки
// группируют их, звёздочка — подстановочный знак. Пользовательская строка,
// вставленная сырой, ломает разбор и позволяет дописать в фильтр свои условия.
//
// Запросы дополнительно ограничены `.eq("user_id", …)` отдельным AND-условием,
// поэтому дотянуться до чужих строк через `or` нельзя — но полагаться на это
// как на единственную защиту не стоит: любой новый запрос без такого скоупа
// сразу стал бы дырой. Поэтому чистим ввод здесь, в одном месте.

/** Максимальная длина поисковой строки — длиннее не несёт смысла и грузит БД. */
const MAX_QUERY = 100;

/**
 * Готовит пользовательскую строку к вставке в PostgREST-фильтр: убирает
 * управляющие символы языка фильтров и обрезает длину. Возвращает null, если
 * после очистки искать нечего — вызывающий код тогда просто не добавляет фильтр.
 */
export function safeSearchTerm(raw: string | null | undefined): string | null {
  if (!raw) return null;
  const cleaned = raw
    .slice(0, MAX_QUERY)
    .replace(/[,()*\\"']/g, " ")  // разделители, группировка, wildcard, кавычки
    .replace(/\s+/g, " ")
    .trim();
  return cleaned.length > 0 ? cleaned : null;
}
